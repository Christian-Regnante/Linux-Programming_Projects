import random
import statistics
import time

import fast_stats
import stats_baseline


SIZES = (1_000, 100_000, 1_000_000)
OPERATIONS = (
    ("mean", lambda module, data: module.calculate_mean(data)),
    ("variance", lambda module, data: module.calculate_variance(data)),
    ("min_max", lambda module, data: module.find_min_max(data)),
    ("outliers", lambda module, data: module.count_outliers(data, 2.0)),
    ("normalize", lambda module, data: module.normalize_data(data)),
)


def measure(function, data, repeats=5):
    samples = []
    for _ in range(repeats):
        start = time.perf_counter()
        function(data)
        samples.append(time.perf_counter() - start)
    return statistics.mean(samples)


def main():
    random.seed(20261030)
    rows = []
    for size in SIZES:
        data = [random.uniform(-5.0, 5.0) for _ in range(size)]
        for name, operation in OPERATIONS:
            python_time = measure(lambda values: operation(stats_baseline, values), data)
            c_time = measure(lambda values: operation(fast_stats, values), data)
            rows.append((size, name, python_time, c_time, python_time / c_time))
            print(f"{size:>8} {name:>10} Python={python_time:.6f}s "
                  f"C={c_time:.6f}s speedup={python_time / c_time:.2f}x")
    with open("benchmark_results.md", "w", encoding="utf-8") as report:
        report.write("# Benchmark Results\n\n")
        report.write("Generated by `benchmark.py` on this machine with seed `20261030`; "
                     "each cell is the mean of five `perf_counter()` runs.\n\n")
        report.write("| Dataset | Operation | Python (s) | C extension (s) | Speedup |\n")
        report.write("| ---: | :--- | ---: | ---: | ---: |\n")
        for size, name, python_time, c_time, speedup in rows:
            report.write(f"| {size:,} | {name} | {python_time:.6f} | "
                         f"{c_time:.6f} | {speedup:.2f}x |\n")
        report.write("\nThe C implementation pays one conversion pass and, for normalization, "
                     "Python-list allocation. The measured speedups therefore reflect the "
                     "complete extension call rather than only the inner arithmetic loop.\n")


if __name__ == "__main__":
    main()
